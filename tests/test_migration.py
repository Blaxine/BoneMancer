"""Files saved by older BoneMancer versions open with their groups intact.

Each legacy file is generated by a vendored copy of the old module in a separate
Blender process: by this Blender, and by every older Blender passed to run.py
(a 4.x file opened in 5.x stores the data differently).
"""

import os
import re
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import bpy
from helpers import check, finish, load_addon, tmp_dir, other_blenders, LEGACY_DIR

FORMATS = {
    "scene": "bonemancer_04883fb.py",
}
LEGACY_KEY = "rmv2_groups_Hero_Rig_001"


def blender_version(binary):
    out = subprocess.run([binary, "--version"], capture_output=True, text=True, errors="replace").stdout
    m = re.search(r"Blender (\d+)\.(\d+)", out)
    return (int(m.group(1)), int(m.group(2))) if m else (0, 0)


def generate(binary, fmt, out_path):
    cmd = [binary, "-b", "--factory-startup", "--python-exit-code", "1",
           "--python", os.path.join(LEGACY_DIR, "make_legacy.py"), "--",
           os.path.join(LEGACY_DIR, FORMATS[fmt]), out_path, fmt]
    proc = subprocess.run(cmd, capture_output=True, text=True, errors="replace", timeout=300)
    if proc.returncode != 0 or not os.path.isfile(out_path):
        raise RuntimeError("legacy file not generated:\n" + (proc.stdout + proc.stderr)[-1500:])


def state():
    sc = bpy.context.scene
    rig = bpy.data.objects["Hero Rig.001"]
    groups = [(g.group_name, g.show_expanded,
               [(b.bone_name, b.show_custom_props, b.show_constraints) for b in g.bones])
              for g in rig.rmv2_groups]
    leftovers = [k for k in sc.keys() if k.startswith("rmv2_groups_")]
    leftovers += [k for k in (LEGACY_KEY,) if mod._read_legacy_groups(sc, k)[0]]
    return {
        "groups": groups,
        "legacy_left": leftovers,
        "picked": sc.rmv2_rig.name if sc.rmv2_rig else None,
        "prop_groups": len(bpy.data.objects["Prop"].rmv2_groups),
    }


EXPECTED = {
    "groups": [("Body", True, [("spine", False, False), ("head", False, True)])],
    "legacy_left": [],
    "picked": "Hero Rig.001",
    "prop_groups": 0,
}

mod = load_addon()
check("register()", mod.register)

me = bpy.app.binary_path
my_version = blender_version(me)
generators = [(me, "this Blender")]
generators += [(b, f"Blender {'.'.join(map(str, v))}") for b in other_blenders()
               for v in [blender_version(b)] if v < my_version]

work = tmp_dir()
for i, (binary, label) in enumerate(generators):
    for fmt in FORMATS:
        path = os.path.join(work, f"legacy_{fmt}_{i}.blend")

        def migrate():
            generate(binary, fmt, path)
            bpy.ops.wm.open_mainfile(filepath=path)
            got = state()
            return (got == EXPECTED, got)
        check(f"{fmt} format saved by {label} migrates", migrate)

        def stable():
            resaved = os.path.join(work, f"resaved_{fmt}_{i}.blend")
            bpy.ops.wm.save_as_mainfile(filepath=resaved)
            bpy.ops.wm.open_mainfile(filepath=resaved)
            got = state()
            return (got == EXPECTED, got)
        check(f"{fmt} format saved by {label}: migrated file reopens unchanged", stable)

check("unregister()", mod.unregister)
finish()
